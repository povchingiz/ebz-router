export interface QueryToken {
  /** Свёрнутая форма (казахские буквы → русские). */
  raw: string;
  stem: string;
  /** Слово как написал заявитель (для объяснений). */
  orig: string;
}

function rawWords(text: string): string[] {
  return text.toLowerCase().split(/[^a-zа-яёәғқңөұүһіъь0-9]+/).filter(Boolean);
}

export function isStop(foldedWord: string): boolean {
  return STOP.has(foldedWord);
}

export function tokenize(text: string): string[] {
  return analyzeQuery(text).tokens.map((t) => t.raw);
}

export function analyzeQuery(text: string): { tokens: QueryToken[]; folded: string } {
  const tokens: QueryToken[] = [];
  for (const orig of rawWords(text)) {
    const raw = fold(orig);
    if (raw.length < 2 || STOP.has(raw)) continue;
    tokens.push({ raw, stem: stem(raw), orig });
  }
  return { tokens, folded: ' ' + tokens.map((t) => t.raw).join(' ') + ' ' };
}

/**
 * Сопоставление термина индекса с токеном запроса.
 * Длинные корни (>=4) работают как префикс (покрывает падежи и окончания),
 * короткие требуют совпадения основы после среза окончаний.
 */
export function termMatchesToken(term: string, tok: QueryToken): boolean {
  if (term.length >= 4) return tok.raw.startsWith(term) || tok.stem === term;
  return tok.raw === term || tok.stem === term;
}

