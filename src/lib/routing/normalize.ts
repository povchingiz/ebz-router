const KK_SORTED = Array.from(new Set(KK_SUFFIXES)).sort((a, b) => b.length - a.length);
const RU_SORTED = Array.from(new Set(RU_SUFFIXES)).sort((a, b) => b.length - a.length);

/** Срезает одно окончание, оставляя основу не короче minStem. */
function stripOnce(word: string, list: string[], minStem: number): string {
  for (const s of list) {
    if (word.length - s.length >= minStem && word.endsWith(s)) return word.slice(0, word.length - s.length);
  }
  return word;
}

/** Лёгкая лемматизация: до 3 срезов окончаний (казахские агглютинативные цепочки), затем 1 русский. */
export function stem(foldedToken: string): string {
  if (foldedToken.length <= 3 || /\d/.test(foldedToken)) return foldedToken;
  let w = foldedToken;
  for (let i = 0; i < 3; i++) {
    const next = stripOnce(w, KK_SORTED, 3);
    if (next === w) break;
    w = next;
  }
  const ru = stripOnce(w, RU_SORTED, 3);
  return ru;
}

